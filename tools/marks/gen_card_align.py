#!/usr/bin/env python3
"""Generates lib/core/marks/card_align.g.dart.

Word marks are stored by the 15-line muṣḥaf's word numbering (both scripts
agree on it everywhere). The card reader shows a different text (Tanzil),
whose word splits differ in ~94 āyahs — e.g. لَّوۡمَا (15:7) is one card word
but two muṣḥaf words, إِلۡ يَاسِينَ (37:130) the reverse. For just those āyahs
this writes, per card word, the muṣḥaf word range it covers.

Alignment is over consonant skeletons (diacritics dropped, letter variants
folded), so the two orthographies line up character by character.

Run from the repo root:  python3 tools/marks/gen_card_align.py
test/card_align_test.dart checks the output against the app's own tokenizer.
"""
import difflib
import json
import re
import sys

# QuranRepo.tokenize: split on whitespace; a token that is only marks joins
# the word before it (or prefixes the next one at the start).
ANNOTATION = re.compile(
    '^[ؐ-ًؚ-ٰٟۖ-ۭ࣓-ࣿ‍-‏]+$')


def tokenize(ayah):
    out, prefix = [], ''
    for t in re.split(r'\s+', ayah):
        if not t:
            continue
        if ANNOTATION.match(t):
            if out:
                out[-1] += t
            else:
                prefix = t
        else:
            out.append(prefix + t)
            prefix = ''
    return out


def mushaf_words(ayah):
    return [t for t in ayah.split('‌') if t and not t.startswith('۝')]


FOLD = {}
for c in 'أإآٱٲٳ':
    FOLD[c] = 'ا'
for c in 'ىیےۍېئ':
    FOLD[c] = 'ي'
for c in 'ةۃہھۀ':
    FOLD[c] = 'ه'
FOLD['ک'] = 'ك'
FOLD['ؤ'] = 'و'
LETTERS = set('ابتثجحخدذرزسشصضطظعغفقكلمنهوي')


def skeleton(word):
    return ''.join(FOLD.get(c, c) for c in word if FOLD.get(c, c) in LETTERS)


def align(card, mushaf):
    """Per card word: (first, last) muṣḥaf word index it covers."""
    sc, oc, sm, om = [], [], [], []
    for i, w in enumerate(card):
        for ch in skeleton(w):
            sc.append(ch)
            oc.append(i)
    for j, w in enumerate(mushaf):
        for ch in skeleton(w):
            sm.append(ch)
            om.append(j)
    links = [set() for _ in card]
    sm_ = difflib.SequenceMatcher(None, sc, sm, autojunk=False)
    for a, b, n in sm_.get_matching_blocks():
        for k in range(n):
            links[oc[a + k]].add(om[b + k])
    out = []
    for i, l in enumerate(links):
        if l:
            out.append([min(l), max(l)])
        else:
            out.append(None)
    # A card word with no matched letters takes its neighbours' boundary.
    for i, r in enumerate(out):
        if r is None:
            prev = out[i - 1][1] if i and out[i - 1] else 0
            out[i] = [prev, prev]
    # Monotonic and covering: stretch to fill gaps between card words.
    out[0][0] = 0
    out[-1][1] = len(mushaf) - 1
    for i in range(1, len(out)):
        if out[i][0] > out[i - 1][1] + 1:
            out[i][0] = out[i - 1][1] + 1
        if out[i][0] < out[i - 1][0]:
            out[i][0] = out[i - 1][0]
        if out[i][1] < out[i][0]:
            out[i][1] = out[i][0]
    return out


def main():
    meta = json.load(open('assets/quran/meta.json'))
    lines = []
    for script, cdir, mfile in [('uthmani', 'u', 'mushaf_u_text.json'),
                                ('indopak', 'i', 'mushaf_i_text.json')]:
        mtext = json.load(open(f'assets/quran/{mfile}'))
        table = {}
        g = 0
        for m in meta:
            ayahs = json.load(open(f'assets/quran/{cdir}/{m["n"]}.json'))
            for a in ayahs:
                card = tokenize(a)
                mw = mushaf_words(mtext[g])
                if len(card) != len(mw):
                    table[g] = align(card, mw)
                g += 1
        name = 'cardAlignUthmani' if script == 'uthmani' else 'cardAlignIndopak'
        lines.append(f'/// {script}: {len(table)} āyahs. Global āyah → for each card word, the')
        lines.append('/// first and last muṣḥaf word (0-based) it covers, flattened.')
        lines.append(f'const {name} = <int, List<int>>{{')
        for g, rs in table.items():
            flat = ', '.join(f'{a}, {b}' for a, b in rs)
            lines.append(f'  {g}: [{flat}],')
        lines.append('};')
        lines.append('')
        print(f'{script}: {len(table)} āyahs', file=sys.stderr)
    header = [
        '// GENERATED by tools/marks/gen_card_align.py — do not edit by hand.',
        '// Card-reader word → muṣḥaf word ranges, for the āyahs where the two',
        '// texts split words differently. See card_align.dart.',
        '',
    ]
    open('lib/core/marks/card_align.g.dart', 'w').write(
        '\n'.join(header + lines))


if __name__ == '__main__':
    main()
