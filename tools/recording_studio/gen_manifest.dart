// Generates manifest.js for the recording studio (index.html) from the
// app's own data, so every file name matches what the app asks for.
//   dart run tools/recording_studio/gen_manifest.dart
import 'dart:convert';
import 'dart:io';

import '../../lib/data/extra_letters.dart';
import '../../lib/data/letters.dart';
import '../../lib/data/makharij.dart';
import '../../lib/data/tashkeel.dart';

/// 'بَ' → '0628-064e' — the LetterAudio naming (lib/core/letter_audio.dart).
String cp(String s) =>
    s.runes.map((r) => r.toRadixString(16).padLeft(4, '0')).join('-');

const audioRoot = 'assets/audio/letters/adult';
const fatha = 'َ', kasra = 'ِ', damma = 'ُ';
const sukun = 'ْ', shadda = 'ّ';

/// The carrier a vowel sits on: alif takes its vowel on a hamzah.
String carrier(String ch) => ch == 'ا' ? 'أ' : ch;

void main() {
  final items = <Map<String, Object?>>[];
  void audio(String section, String text, String say,
      {String priority = 'core', String? note}) {
    items.add({
      'id': 'audio:${cp(text)}',
      'kind': 'audio',
      'section': section,
      'text': text,
      'say': say,
      'priority': priority,
      if (note != null) 'note': note,
      'path': '$audioRoot/${cp(text)}',
    });
  }

  // 1 · letter names
  for (final l in letters) {
    audio('1 · Letter names', l.char, 'Say its name: ${l.name}');
  }
  // 2 · the extra letters
  for (final l in extraLetters) {
    audio('2 · Beyond the 28', l.char, 'Say its name: ${l.name}');
  }
  // 3-4 · ḥarakāt and tanwīn syllables
  for (final (mark, name, sound) in harakat) {
    for (final l in letters) {
      final c = carrier(l.char);
      final t = l.translit == 'ā' ? '' : l.translit;
      audio('3 · Ḥarakāt — $name', '$c$mark', 'Say: $t$sound  (one count)');
    }
  }
  for (final (mark, name, sound) in tanwin) {
    for (final l in letters) {
      final c = carrier(l.char);
      final t = l.translit == 'ā' ? '' : l.translit;
      audio('4 · Tanwīn — $name', '$c$mark', 'Say: $t$sound');
    }
  }
  // 5 · madd: the long vowels (two counts)
  for (final l in letters) {
    final c = carrier(l.char);
    final t = l.translit == 'ā' ? '' : l.translit;
    final first = c == 'أ' ? 'آ' : '$c${fatha}ا';
    audio('5 · Madd (2 counts)', first, 'Say: ${t}ā — hold two counts',
        priority: 'next');
    audio('5 · Madd (2 counts)', '$c${kasra}ي', 'Say: ${t}ī — hold two counts',
        priority: 'next');
    audio('5 · Madd (2 counts)', '$c${damma}و', 'Say: ${t}ū — hold two counts',
        priority: 'next');
  }
  // 6 · sukūn and shaddah, joined to a vowel before them (أَبْ, أَبَّ)
  for (final l in letters.where((l) => l.char != 'ا')) {
    audio('6 · Sukūn', 'أَ${l.char}$sukun', 'Say: a${l.translit} (stop on it)',
        priority: 'next');
  }
  for (final l in letters.where((l) => l.char != 'ا')) {
    audio('7 · Shaddah', 'أَ${l.char}$shadda$fatha',
        'Say: a${l.translit}${l.translit}a (press on it twice)',
        priority: 'next');
  }
  // 8 · the letters' example words (beginning · middle · end)
  final seen = <String>{};
  for (final l in letters) {
    for (final w in letterExamples[l.char] ?? const <LetterExample>[]) {
      if (!seen.add(w.word)) continue;
      audio('8 · Example words', w.word, 'Read the word: ${w.translit}',
          priority: 'later',
          note: '${l.name} · ${w.position}');
    }
  }

  // ── video ──
  void video(String section, String id, String text, String say) {
    items.add({
      'id': 'video:$section:$id',
      'kind': 'video',
      'section': section,
      'text': text,
      'say': say,
      'priority': 'core',
      'path': 'assets/video/${section.split(' · ').last.toLowerCase().replaceAll(' ', '_')}/$id',
    });
  }

  for (final l in letters) {
    video('V1 · Letters', cp(l.char), l.char,
        'Face the camera, mouth in frame. Say “${l.name}”, then the letter with a fatḥah, twice.');
  }
  for (final m in makharij) {
    video('V2 · Makharij', m.id, m.letters.isEmpty ? m.arabicName : m.letters.split('').join(' '),
        '${m.name} (${m.arabicName}) — show where it is, then say its letters slowly.');
  }
  for (final t in tashkil) {
    video('V3 · Tashkil', t.id, t.mark,
        t.sound.trim().isEmpty || t.sound.contains('—')
            ? '${t.name}: show the mark and read an example word with it.'
            : '${t.name}: show the mouth shape and say “${t.sound}”${t.counts > 1 ? ' for ${t.counts} counts' : ''}.');
  }

  final out = File('tools/recording_studio/manifest.js');
  out.writeAsStringSync('// Generated by gen_manifest.dart — do not edit.\n'
      'window.MANIFEST = ${const JsonEncoder.withIndent(' ').convert(items)};\n');
  final a = items.where((i) => i['kind'] == 'audio').length;
  stdout.writeln('${items.length} items ($a audio, ${items.length - a} video)');
}
