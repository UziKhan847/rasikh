"""Builds Kids Mode's bundled fonts from the upstream files the design uses.

    python3 tool/kb_fonts.py <dir-with-downloads>

<dir> must hold the upstream files (Google Fonts / google/material-design-icons):
  BalooBhaijaan2.ttf            BalooBhaijaan2[wght].ttf
  NotoNaskhArabic.ttf           NotoNaskhArabic[wght].ttf
  AmiriQuran-Regular.ttf        AmiriQuran-Regular.ttf
  MSR.ttf / MSR.codepoints      MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf/.codepoints

Variable fonts are cut into static instances, as with Baloo2: a variable font
is a known trigger for Skia text-shaper hangs on some Android GPU drivers (see
CREDITS.md). The icon font is 15 MB upstream; it is instanced at the design's
exact axes (FILL 1, wght 600, GRAD 0, opsz 24) and subset to the icons listed in
tool/kb_icons.txt, and lib/kids_backdrops/kb_icons.dart is regenerated to map
each name to its codepoint.
"""
import os, shutil, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'assets', 'fonts')

def static(name, family, weight, dest):
    f = TTFont(os.path.join(src, name))
    instantiateVariableFont(f, {'wght': weight}, inplace=True, updateFontNames=False)
    f.save(os.path.join(out, dest))
    print(f'  {dest}: {os.path.getsize(os.path.join(out, dest)) // 1024} KB')

for w, n in [(500, 'Medium'), (600, 'SemiBold'), (700, 'Bold'), (800, 'ExtraBold')]:
    static('BalooBhaijaan2.ttf', 'Baloo Bhaijaan 2', w, f'BalooBhaijaan2-{n}.ttf')
for w, n in [(500, 'Medium'), (600, 'SemiBold')]:
    static('NotoNaskhArabic.ttf', 'Noto Naskh Arabic', w, f'NotoNaskhArabic-{n}.ttf')
shutil.copy(os.path.join(src, 'AmiriQuran-Regular.ttf'), os.path.join(out, 'AmiriQuran-Regular.ttf'))
print('  AmiriQuran-Regular.ttf copied')

# ── icons ──
points = {}
for line in open(os.path.join(src, 'MSR.codepoints')):
    k, v = line.split()
    points[k] = int(v, 16)
names = [l.strip() for l in open(os.path.join(root, 'tool', 'kb_icons.txt'))
         if l.strip() and not l.startswith('#')]
missing = [n for n in names if n not in points]
if missing:
    sys.exit(f'not in Material Symbols Rounded: {missing}')

icons = TTFont(os.path.join(src, 'MSR.ttf'))
instantiateVariableFont(icons, {'FILL': 1, 'wght': 600, 'GRAD': 0, 'opsz': 24}, inplace=True)
opts = subset.Options()
opts.layout_features = []          # addressed by codepoint, not by ligature
opts.notdef_outline = True
opts.name_IDs = ['*']
s = subset.Subsetter(opts)
s.populate(unicodes=[points[n] for n in names])
s.subset(icons)
dest = os.path.join(out, 'MaterialSymbolsRounded-Kids.ttf')
icons.save(dest)
print(f'  MaterialSymbolsRounded-Kids.ttf: {os.path.getsize(dest) // 1024} KB, {len(names)} icons')

lines = ['// GENERATED by tool/kb_fonts.py from tool/kb_icons.txt — do not hand-edit.',
         '// Material Symbols Rounded codepoints for the icons bundled in',
         '// assets/fonts/MaterialSymbolsRounded-Kids.ttf (FILL 1, wght 600).',
         '', 'const Map<String, int> kbIconCodepoints = {']
lines += [f"  '{n}': 0x{points[n]:x}," for n in names] + ['};', '']
open(os.path.join(root, 'lib', 'kids_backdrops', 'kb_icons.dart'), 'w').write('\n'.join(lines))
print('  lib/kids_backdrops/kb_icons.dart regenerated')
