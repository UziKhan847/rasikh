"""Writes lib/data/divisions.dart: where every rubʿ (quarter-ḥizb), manzil
and rukūʿ of the muṣḥaf starts.

    python3 tool/gen_divisions.py path/to/quran-data.js

quran-data.js is Tanzil's Qur'an metadata (https://tanzil.net/res/text/
metadata/quran-data.js, CC BY 3.0). The muṣḥaf text decides wherever it
can:

  - rubʿ: the ۞ the Madani text prints (199 of them) are taken as they are;
    a quarter that opens a sūrah has no ۞ (the sūrah header stands in), and
    those come from Tanzil's list — which must agree on every other quarter.
    (Tanzil puts one quarter at 15:50; the text prints ۞ at 15:49.)
  - manzil: Tanzil's seven starts.
  - rukūʿ: after every ࣖ the Indo-Pak text prints (558, one ending every
    sūrah), so the count matches the Indo-Pak muṣḥaf the sign comes from.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))


def load(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as f:
        return json.load(f)


def tanzil(js, name):
    b = js[js.index(f'QuranData.{name} = ['):]
    b = b[:b.index('];')]
    return [(int(s), int(a)) for s, a in re.findall(r'\[(\d+),\s*(\d+)\]', b)]


def main():
    js = open(sys.argv[1], encoding='utf-8').read()
    meta = load('assets/quran/meta.json')
    cum = [0]
    for m in meta:
        cum.append(cum[-1] + m['ayahs'])
    total = cum[-1]

    def g(s, a):
        return cum[s - 1] + a - 1

    def sa(x):
        s = max(k for k in range(len(cum) - 1) if cum[k] <= x)
        return (s + 1, x - cum[s] + 1)

    u = load('assets/quran/mushaf_u_text.json')
    marked = {a for a, s in enumerate(u) if '۞' in s}
    quarters = {g(s, a) for s, a in tanzil(js, 'HizbQaurter')
                if g(s, a) < total}  # the list ends with a past-the-end entry
    unmarked = quarters - marked
    sura_start = {cum[k] for k in range(114)}
    # Allowed disagreement: Tanzil's 15:50 where the text marks 15:49.
    if marked - quarters != {g(15, 49)} or unmarked - sura_start != {g(15, 50)}:
        sys.exit(f'rubʿ lists disagree: text-only {[sa(x) for x in marked - quarters]}, '
                 f'Tanzil-only {[sa(x) for x in unmarked - sura_start]}')
    rub = sorted(marked | (unmarked & sura_start))
    if len(rub) != 240:
        sys.exit(f'{len(rub)} quarters, not 240')

    manzil = sorted(g(s, a) for s, a in tanzil(js, 'Manzil'))
    if len(manzil) != 7:
        sys.exit('not 7 manāzil')

    i = load('assets/quran/mushaf_i_text.json')
    ends = [a for a, s in enumerate(i) if 'ࣖ' in s]
    if not all(cum[k] - 1 in set(ends) for k in range(1, 115)):
        sys.exit('a sūrah ends without ࣖ')
    ruku = sorted({0} | {a + 1 for a in ends if a + 1 < total})

    def table(xs):
        cells = [f'({s}, {a})' for s, a in map(sa, xs)]
        rows = [', '.join(cells[k:k + 8]) for k in range(0, len(cells), 8)]
        return '\n'.join(f'  {r},' for r in rows)

    out = f'''// GENERATED by tool/gen_divisions.py — do not edit by hand.
//
// Where the muṣḥaf's divisions start, as (sūrah, āyah), both 1-based. The
// rubʿ starts are the ۞ printed in the Madani text plus the sūrah openings
// that carry no ۞; manāzil from Tanzil's metadata (tanzil.net, CC BY 3.0);
// rukūʿ after each ࣖ printed in the Indo-Pak text.

/// The 240 quarter-ḥizb (rubʿ) starts. Ḥizb n starts at quarter 4n − 3;
/// juzʼ n at quarter 8n − 7.
const rubStarts = <(int, int)>[
{table(rub)}
];

/// The seven manāzil starts.
const manzilStarts = <(int, int)>[
{table(manzil)}
];

/// The {len(ruku)} rukūʿ starts.
const rukuStarts = <(int, int)>[
{table(ruku)}
];
'''
    path = os.path.join(ROOT, 'lib', 'data', 'divisions_data.dart')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(out)
    print(f'rubʿ {len(rub)}, manāzil {len(manzil)}, rukūʿ {len(ruku)} → {path}')


if __name__ == '__main__':
    main()
