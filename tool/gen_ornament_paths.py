"""Extracts the Classic ornament artwork (single-path SVGs from the design
handoff) into lib/ui/classic_ornament_paths.dart: each drawing's path data,
viewBox size and the group translation, for Dart to build Paths from.

    python3 tool/gen_ornament_paths.py
"""
import re

SRC = 'design_handoff_qiraah_flutter/flutter/assets/ornaments/'
OUT = 'lib/ui/classic_ornament_paths.dart'
ART = [('verse_circle', 'verseCircle'), ('surah_border', 'surahBorder'),
       ('lantern', 'lantern')]

out = ['// Generated by tool/gen_ornament_paths.py from the Classic ornament',
       '// artwork (design handoff, Update 8): each drawing\'s one path, in its',
       '// SVG viewBox units, and the offset its group adds.', '']
for name, const in ART:
    s = open(SRC + name + '.svg').read()
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()]
    tr = re.search(r'transform="translate\(([-\d.e]+),([-\d.e]+)\)"', s)
    ds = re.findall(r'<path[^>]* d="([^"]+)"', s)
    if len(ds) != 1 or 'transform' in re.search(r'<path[^>]*>', s).group(0):
        raise SystemExit(f'{name}: expected one untransformed path')
    d = re.sub(r'\s+', ' ', ds[0]).strip()
    chunks = [d[i:i + 76] for i in range(0, len(d), 76)]
    out += [f'const {const}Svg = (',
            f'  width: {vb[2]},',
            f'  height: {vb[3]},',
            f'  dx: {float(tr.group(1)) - vb[0]},',
            f'  dy: {float(tr.group(2)) - vb[1]},',
            '  d: ' + '\n      '.join(f"'{c}'" for c in chunks) + ',',
            ');', '']
open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}')
