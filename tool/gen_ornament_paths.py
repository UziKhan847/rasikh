"""Extracts the muṣḥaf's ornament artwork (SVGs from the design handoff)
into lib/ui/ornaments/paths.dart: each drawing's paths, each path's fill
colour, the viewBox size and the group translation, for Dart to build
Paths from. (The Madani page border, a nine-slice of coloured tiles, is
written out by hand in page_borders.dart.)

The Indo-Pak two-tier header comes with its basmala drawn in; it is split
into the border and the basmala (the paths inside the lower band), so the
border can be widened and the basmala drawn at its own proportions. That
uses Inkscape for the paths' bounding boxes.

    python3 tool/gen_ornament_paths.py
"""
import re
import subprocess

SRC = 'design_handoff_qiraah_flutter/flutter/assets/ornaments/'
OUT = 'lib/ui/ornaments/paths.dart'

# (file, Dart name, which paths: None for all, or 'border' / 'basmala' of
# the Indo-Pak two-tier header).
ART = [
    ('surah_border', 'surahBorder', None),
    ('surah_border_madani_coloured', 'surahBorderColoured', None),
    ('madani_margin_lantern_1', 'lantern1', None),
    ('madani_margin_lantern_2', 'lantern2', None),
    ('indopak_verse_circle', 'indopakVerseCircle', None),
    ('surah_border_with_basmala_indo_pak_2', 'indopakSurahBorder', 'border'),
    ('surah_border_with_basmala_indo_pak_2', 'indopakBasmala', 'basmala'),
    ('indopak_surah_header', 'indopakSurahHeader', None),
    ('indopak_page_border', 'indopakPageBorder', None),
]

NUM = re.compile(r'-?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?')


def rounded(d):
    """[d] with its numbers at 3 decimals (the artwork is hundreds of units
    wide, so that's far below a pixel), and no redundant zeros."""
    def fmt(m):
        v = round(float(m.group(0)), 3)
        s = f'{v:.3f}'.rstrip('0').rstrip('.')
        return '0' if s in ('-0', '') else s
    return re.sub(r'\s+', ' ', NUM.sub(fmt, d)).strip()


def fill_of(tag):
    m = re.search(r'fill:\s*(#[0-9a-fA-F]{6})', tag) or \
        re.search(r'\bfill="(#[0-9a-fA-F]{6})"', tag)
    return int('FF' + (m.group(1)[1:] if m else '000000'), 16)


def basmala_ids(path):
    """The paths of the Indo-Pak header's basmala (with its small circle):
    those inside the lower band's middle, away from its corner ornaments."""
    out = subprocess.run(['inkscape', '--query-all', path],
                         capture_output=True, text=True, check=True).stdout
    rows = [r.split(',') for r in out.strip().splitlines()]
    _, _, _, W, H = rows[0]
    W, H = float(W), float(H)
    ids = set()
    for pid, x, y, w, h in rows[1:]:
        x, y, w, h = (float(v) / s for v, s in ((x, W), (y, H), (w, W), (h, H)))
        # (Letter tails reach the band's bottom line; the line's own
        # pieces are long and flat.)
        if (x >= .18 and x + w <= .83 and y >= .53 and y + h <= .999
                and w < .19 and .03 <= h < .43):
            ids.add(pid)
    if len(ids) < 20:
        raise SystemExit(f'basmala: only {len(ids)} paths found')
    return ids


out = ['// Generated by tool/gen_ornament_paths.py from the ornament artwork',
       '// (design handoff): each drawing\'s paths in its SVG viewBox units,',
       '// each path\'s fill (ARGB), and the offset its group adds.', '']
for name, const, part in ART:
    path = SRC + name + '.svg'
    s = open(path).read()
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()]
    tr = re.search(r'transform="translate\(([-\d.e]+),([-\d.e]+)\)"', s)
    dx, dy = (float(tr.group(1)), float(tr.group(2))) if tr else (0.0, 0.0)
    tags = re.findall(r'<path\b[^>]*>', s)
    if any(re.search(r'\stransform=', t) for t in tags):
        raise SystemExit(f'{name}: a path has its own transform')
    if part:
        ids = basmala_ids(path)
        keep = (lambda t: re.search(r'\bid="([^"]+)"', t).group(1) in ids) \
            if part == 'basmala' else \
            (lambda t: re.search(r'\bid="([^"]+)"', t).group(1) not in ids)
        tags = [t for t in tags if keep(t)]
    out += [f'const {const}Svg = (',
            f'  width: {vb[2]},',
            f'  height: {vb[3]},',
            f'  dx: {round(dx - vb[0], 5)},',
            f'  dy: {round(dy - vb[1], 5)},',
            '  fills: [' + ', '.join(f'0x{fill_of(t):08X}' for t in tags) + '],',
            '  d: [']
    for t in tags:
        d = rounded(re.search(r'\bd="([^"]+)"', t).group(1))
        chunks = [d[i:i + 74] for i in range(0, len(d), 74)]
        out.append('    ' + '\n        '.join(f"'{c}'" for c in chunks) + ',')
    out += ['  ],', ');', '']
open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}')
