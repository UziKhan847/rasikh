"""Extracts the Classic ornament artwork (single-colour SVGs from the design
handoff) into lib/ui/classic_ornament_paths.dart: each drawing's paths (one
or more, each filled on its own), viewBox size and the group translation,
for Dart to build Paths from. (The Madani page border, a nine-slice of
coloured tiles, is written out by hand in classic_ornaments.dart.)

    python3 tool/gen_ornament_paths.py
"""
import re

SRC = 'design_handoff_qiraah_flutter/flutter/assets/ornaments/'
OUT = 'lib/ui/classic_ornament_paths.dart'
ART = [('verse_circle', 'verseCircle'), ('surah_border', 'surahBorder'),
       ('lantern', 'lantern'), ('indopak_verse_circle', 'indopakVerseCircle'),
       ('indopak_surah_border', 'indopakSurahBorder'),
       ('indopak_surah_border_tawbah', 'indopakSurahBorderTawbah'),
       ('indopak_page_border', 'indopakPageBorder')]

out = ['// Generated by tool/gen_ornament_paths.py from the Classic ornament',
       '// artwork (design handoff, Updates 8 and 9): each drawing\'s paths, in',
       '// its SVG viewBox units, and the offset its group adds.', '']
for name, const in ART:
    s = open(SRC + name + '.svg').read()
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()]
    tr = re.search(r'transform="translate\(([-\d.e]+),([-\d.e]+)\)"', s)
    dx, dy = (float(tr.group(1)), float(tr.group(2))) if tr else (0.0, 0.0)
    tags = re.findall(r'<path\b[^>]*>', s)
    if any('transform' in t for t in tags):
        raise SystemExit(f'{name}: a path has its own transform')
    ds = [re.sub(r'\s+', ' ', re.search(r'\bd="([^"]+)"', t).group(1)).strip()
          for t in tags]
    out += [f'const {const}Svg = (',
            f'  width: {vb[2]},',
            f'  height: {vb[3]},',
            f'  dx: {dx - vb[0]},',
            f'  dy: {dy - vb[1]},',
            '  d: [']
    for d in ds:
        chunks = [d[i:i + 74] for i in range(0, len(d), 74)]
        out.append('    ' + '\n        '.join(f"'{c}'" for c in chunks) + ',')
    out += ['  ],', ');', '']
open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}')
