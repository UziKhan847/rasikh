import '../../data/letters.dart';
import 'families.dart';

/// The recordings the Qāʿidah can use, and where each goes: what to record
/// (for the Sheikh, or whoever records them), in the order to record them.
/// The app plays a recording wherever its file is bundled, and offers no
/// listening where it isn't (see LetterAudio). Kept in
/// docs/qaidah_audio_manifest.md and .csv by tool/gen_qaidah_audio_manifest.dart;
/// a test checks those are up to date.
class AudioClip {
  final String text, kind, usedBy;
  final int priority;
  const AudioClip(this.text, this.kind, this.usedBy, this.priority);

  /// The asset, as LetterAudio looks for it (adult voice).
  String get path =>
      'assets/audio/letters/adult/${text.runes.map((r) => r.toRadixString(16).padLeft(4, '0')).join('-')}.mp3';
}

const _fatha = 'َ', _kasra = 'ِ', _damma = 'ُ';
const _fathatan = 'ً', _kasratan = 'ٍ', _dammatan = 'ٌ';
const _sukun = 'ْ';

List<AudioClip> qaidahAudioClips() => [
      // 1. Each letter's name, in its family's lesson.
      for (final f in letterFamilies)
        for (final c in f.chars) AudioClip(c, 'name', 'lesson ${f.id}', 1),
      // 2. Each letter with each short vowel: ba, bi, bu.
      for (final l in letters)
        for (final v in [_fatha, _kasra, _damma])
          if (l.char != 'ا') AudioClip('${l.char}$v', 'syllable', 'Ḥarakāt', 2),
      // 3. Long vowels: bā, bī, bū.
      for (final l in letters)
        if (l.char != 'ا') ...[
          AudioClip('${l.char}$_fathaا', 'madd', 'Madd & Līn', 3),
          AudioClip('${l.char}$_kasraي', 'madd', 'Madd & Līn', 3),
          AudioClip('${l.char}$_dammaو', 'madd', 'Madd & Līn', 3),
        ],
      // 4. Tanwīn: ban, bin, bun.
      for (final l in letters)
        if (l.char != 'ا')
          for (final v in [_fathatan, _kasratan, _dammatan])
            AudioClip('${l.char}$v', 'tanwin', 'Tanwīn', 4),
      // 5. A letter at rest after a vowel: ab.
      for (final l in letters)
        if (l.char != 'ا') AudioClip('أَ${l.char}$_sukun', 'sukun', 'Sukūn', 5),
    ];

/// The manifest as Markdown.
String qaidahAudioMarkdown() {
  final clips = qaidahAudioClips();
  final b = StringBuffer()
    ..writeln('# Qāʿidah recordings')
    ..writeln()
    ..writeln('What the Qāʿidah can play, once recorded: ${clips.length} clips, in the order to record them (priority 1 first).')
    ..writeln('Each goes at its path as an MP3 (mono, 44.1 kHz is plenty); the app offers listening wherever a file is present and nowhere else.')
    ..writeln('With the first file, add `assets/audio/letters/adult/` to the assets in `pubspec.yaml`.')
    ..writeln('Generated by `tool/gen_qaidah_audio_manifest.dart` — edit `lib/learn/qaidah/audio_manifest.dart`, not this file.')
    ..writeln()
    ..writeln('| # | Say | Kind | Used in | Priority | File |')
    ..writeln('|---|---|---|---|---|---|');
  for (final (i, c) in clips.indexed) {
    b.writeln('| ${i + 1} | ${c.text} | ${c.kind} | ${c.usedBy} | ${c.priority} | `${c.path}` |');
  }
  return b.toString();
}

/// The manifest as CSV.
String qaidahAudioCsv() {
  final b = StringBuffer()..writeln('n,text,kind,used_by,priority,file');
  for (final (i, c) in qaidahAudioClips().indexed) {
    b.writeln('${i + 1},${c.text},${c.kind},"${c.usedBy}",${c.priority},${c.path}');
  }
  return b.toString();
}
