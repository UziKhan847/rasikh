/// Muṣḥaf letter shapes the tatweel-based joining forms (letters.dart's
/// `initial`/`medial`/`finalForm` getters) cannot show — kāf wrapping a
/// following alif/lām, a middle tooth-letter riding higher between two
/// others, cursive mīm/lām stacking over jīm/ḥāʾ/khāʾ, the lām-alif
/// ligature, and the dotless final/isolated yāʾ.
///
/// [word] is verbatim Uthmani, found by searching assets/quran/u/ for the
/// base-letter sequence that triggers each shape in UthmanicHafs's GSUB
/// rules (see the plan's font census) — never hand-picked. UthmanicHafs
/// then shapes it correctly on its own; Flutter cannot address a glyph
/// variant directly, so every variant must be demonstrated by real text.
///
/// TODO(variants): a fontTools -> Dart-path generator could additionally
/// render each shape in isolation, the way strokes_gen.dart does for
/// tracing letterforms.
///
/// Generated by a throwaway script (see the plan) against a systematic
/// census of 116 positional + 39 genuine extra allographs across all 36
/// letters in UthmanicHafs.ttf. Not every allograph found is here — single-
/// word special-case forms (e.g. a whole-word fāʾ ligature, the mīm shapes
/// that only fire before a following kasratān) were reviewed and dropped
/// as not worth a lesson; this is the curated, teachable subset.
class LetterVariant {
  final String id;
  final String letter; // base letter(s) this variant belongs to
  final String kind; // 'positional' | 'ligature' | 'stacked' | 'small'
  final String word; // verbatim Uthmani word that renders it
  final String ref; // surah:ayah
  final String highlight; // substring of word carrying the variant

  const LetterVariant(this.id, this.letter, this.kind, this.word, this.ref,
      this.highlight);
}

